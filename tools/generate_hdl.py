#!/usr/bin/env python3
"""Convierte el diseño MyHDL a VHDL.

Genera:

* ``hdl/candado_top.vhd``          top plano para la placa (parámetros HW).
* ``hdl/candado_top_sim.vhd``      mismo top con tiempos reducidos (SIM) para GHDL/xsim.
* ``hdl/modules/<modulo>.vhd``     cada módulo convertido por separado (estudio y revisión).
* ``hdl/pck_myhdl_011.vhd``        paquete de apoyo de MyHDL (se agrega a Vivado).

Uso: ``python tools/generate_hdl.py [--outdir hdl]``
"""

import argparse
import os
import re
import shutil
import sys
import warnings

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from myhdl import Signal, ToVHDLWarning, intbv  # noqa: E402

from candado.core import candado_core  # noqa: E402
from candado.datapath import code_comparator, code_register, digit_buffer  # noqa: E402
from candado.display import display_driver  # noqa: E402
from candado.fsm import fsm_control  # noqa: E402
from candado.inputs import debouncer, synchronizer  # noqa: E402
from candado.params import HW, SIM  # noqa: E402
from candado.status import status_outputs  # noqa: E402
from candado.timebase import tick_timer  # noqa: E402
from candado.top import candado_top  # noqa: E402
from candado.uart import event_logger, uart_tx  # noqa: E402


def b():
    return Signal(False)


def v(n):
    return Signal(intbv(0)[n:])


def r(lo, hi):
    return Signal(intbv(0, min=lo, max=hi))


def convert(inst, name, path, std_logic_ports=True):
    inst.convert(hdl="VHDL", name=name, path=path, initial_values=True,
                 std_logic_ports=std_logic_ports)


def top_instance(p):
    return candado_top(
        Signal(False), Signal(True), v(16), b(), b(), b(), b(), b(),
        v(16), v(7), Signal(True), v(8), b(), b(), b(), Signal(True), p=p)


def module_instances(p):
    """(nombre, instancia) de cada módulo con sus parámetros de HW."""
    return [
        ("synchronizer", synchronizer(b(), b(), b())),
        ("debouncer", debouncer(b(), b(), b(), b(), p.debounce_cycles)),
        ("tick_timer", tick_timer(b(), b(), b(), p.tick_cycles)),
        ("digit_buffer", digit_buffer(b(), b(), b(), b(), b(), v(4), r(0, 5), v(16))),
        ("code_register", code_register(b(), b(), b(), v(16), Signal(intbv(p.default_code)[16:]), p.default_code)),
        ("code_comparator", code_comparator(v(16), v(16), b())),
        ("fsm_control", fsm_control(
            b(), b(), b(), b(), b(), b(), r(0, 5), b(), b(),
            v(3), b(), b(), b(), b(), b(), r(0, p.max_attempts + 1),
            p.error_ticks, p.unlocked_ticks, p.alarm_ticks, p.config_ticks,
            p.max_attempts, p.tick_max)),
        ("display_driver", display_driver(
            b(), v(3), r(0, p.max_attempts + 1), v(7), v(8), p.scan_bits)),
        ("status_outputs", status_outputs(b(), v(3), r(0, 5), v(16), v(3), p.pwm_bits)),
        ("uart_tx", uart_tx(b(), b(), v(8), b(), b(), b(), p.baud_cycles)),
        ("event_logger", event_logger(
            b(), b(), v(3), r(0, p.max_attempts + 1), b(), p.baud_cycles)),
        ("candado_core", candado_core(
            b(), b(), b(), b(), b(), v(4), b(), v(3), r(0, 5),
            r(0, p.max_attempts + 1), r(0, p.max_attempts + 1),
            Signal(intbv(p.default_code)[16:]),
            p.debounce_cycles, p.tick_cycles, p.error_ticks, p.unlocked_ticks,
            p.alarm_ticks, p.config_ticks, p.max_attempts, p.tick_max,
            p.default_code)),
    ]


def _sorted_sensitivity(m):
    names = sorted(n.strip() for n in m.group(2).split(","))
    return f"{m.group(1)}process ({', '.join(names)}) is"


def _hex_literal(m):
    width, digits = int(m.group(1)), m.group(2)
    return f"to_unsigned({int(digits, 16)}, {width})"


def clean_header(path):
    """Postproceso del VHDL generado.

    * Quita fecha/versión del encabezado (salida reproducible).
    * Reemplaza los literales ``16X"0000"`` (sólo VHDL-2008) por
      ``to_unsigned(0, 16)``, válido en VHDL-93 y en VHDL-2008, para que
      Vivado compile los archivos sin cambiar el tipo de archivo.
    * Ordena alfabéticamente las listas de sensibilidad de los procesos: MyHDL
      las construye con conjuntos y su orden cambia entre ejecuciones; así el
      VHDL versionado es idéntico cada vez que se regenera.
    """
    for fn in os.listdir(path):
        if not fn.endswith(".vhd"):
            continue
        full = os.path.join(path, fn)
        text = open(full, encoding="utf-8").read()
        text = re.sub(r"-- Generated by MyHDL [^\n]*\n-- Date: [^\n]*\n",
                      "-- Generated by MyHDL (tools/generate_hdl.py)\n", text)
        text = re.sub(r'(\d+)X"([0-9A-Fa-f]+)"', _hex_literal, text)
        text = re.sub(r"^(\w+: )process \(([^)]*)\) is$", _sorted_sensitivity, text, flags=re.M)
        open(full, "w", encoding="utf-8", newline="\n").write(text)


def main():
    # Avisos esperados: BTNU/BTND reservados (sin uso) y señales *_level sin lector.
    warnings.simplefilter("ignore", ToVHDLWarning)
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--outdir", default="hdl")
    args = ap.parse_args()
    out = args.outdir
    mods = os.path.join(out, "modules")
    os.makedirs(mods, exist_ok=True)

    # Top plano: hardware real y versión de simulación rápida.
    convert(top_instance(HW), "candado_top", out)
    convert(top_instance(SIM), "candado_top_sim", out)

    # Módulos individuales (parámetros de HW).
    for name, inst in module_instances(HW):
        convert(inst, name, mods)

    # Un único paquete de apoyo compartido.
    for fn in os.listdir(mods):
        if fn.startswith("pck_myhdl"):
            os.remove(os.path.join(mods, fn))
    clean_header(out)
    clean_header(mods)
    print(f"VHDL generado en {out}/ y {mods}/")


if __name__ == "__main__":
    main()
